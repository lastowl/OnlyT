namespace OnlyT.Avalonia.Services.Options;

/// <summary>
/// Clock display mode for the timer output window
/// </summary>
public enum FullScreenClockMode
{
    /// <summary>
    /// Show only the analogue clock
    /// </summary>
    Analogue,

    /// <summary>
    /// Show only the digital clock
    /// </summary>
    Digital,

    /// <summary>
    /// Show both analogue and digital clocks
    /// </summary>
    AnalogueAndDigital
}
